/// 逐词翻译一整段短语。任何一个词无法翻译时返回 `None`。
pub(crate) fn translate(text: &str) -> Option<String> {
    let words: Vec<&str> = text.split_whitespace().collect();
    if words.is_empty() {
        return None;
    }

    let mut translated: Vec<&'static str> = Vec::with_capacity(words.len());
    let mut index = 0;
    while index < words.len() {
        let mut span = MAX_SPAN.min(words.len() - index);
        let mut hit = None;
        while span > 0 {
            let candidate = words[index..index + span].join(" ");
            if let Some(value) = lookup(&candidate) {
                hit = Some((span, value));
                break;
            }
            span -= 1;
        }
        let (span, value) = hit?;
        translated.push(value);
        index += span;
    }

    Some(join(&translated))
}

fn lookup(candidate: &str) -> Option<&'static str> {
    let lowered = candidate.to_lowercase();
    if UNSUPPORTED.contains(&lowered.as_str()) {
        return None;
    }
    vocab()
        .iter()
        .find_map(|(english, chinese)| (*english == lowered).then_some(*chinese))
}

/// 中文与中文之间不加空格,其余情况保留空格。
fn join(parts: &[&str]) -> String {
    let mut result = String::new();
    for part in parts {
        let previous_is_cjk = result.chars().next_back().is_some_and(is_cjk);
        let next_is_cjk = part.chars().next().is_some_and(is_cjk);
        if !result.is_empty() && !(previous_is_cjk && next_is_cjk) {
            result.push(' ');
        }
        result.push_str(part);
    }
    result
}

fn is_cjk(character: char) -> bool {
    matches!(
        character as u32,
        0x4E00..=0x9FFF | 0x3000..=0x303F | 0xFF00..=0xFFEF
    )
}

